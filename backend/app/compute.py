"""Сама вычислительная функция.

Специально СИНХРОННАЯ и чистая (без Redis, логгера, глобального состояния): она
выполняется в отдельном процессе ProcessPoolExecutor, куда аргументы и результат
передаются через pickle. Всё, что ей нужно, — это n.
"""


def fibonacci(n: int) -> int:
    # Наивная рекурсия без мемоизации — намеренно: ~φ^N вызовов даёт настоящую
    # CPU-нагрузку, ради которой в проекте есть кэш, лок и пул процессов.
    if n < 2:
        return n
    return fibonacci(n - 1) + fibonacci(n - 2)
